import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs'
import { dirname, join, relative, resolve, sep } from 'node:path'
import { parseJsonc } from './jsonc.js'

export type Framework = 'react' | 'vue'

// How the generated lib/auth.ts reports unexpected auth errors.
//   sonner / vue-sonner: `toast.error(title, { description })` from the package
//   use-toast:           shadcn `toast({ title, description, variant: 'destructive' })`
export type ToastKind = 'sonner' | 'vue-sonner' | 'use-toast'

export interface ToastInfo {
  kind: ToastKind
  // Package name ('sonner') or app-dir-relative module path ('components/ui/toast/use-toast').
  module: string
  appModule: boolean
  // Where it was found (shown in the report).
  source: string
}

export interface EnvInfo {
  // Env variable with the API base URL used by createAuthClient({ baseUrl }).
  key: string
  source: string
  // Env files (project-root-relative) that define the key, and whether one sets a value.
  definedIn: string[]
  hasValue: boolean
}

export interface LoginPageInfo {
  // File that registers the /login route (router / routes.ts) and the page component file.
  routeFile: string
  pageFile: string | null
  // The page already renders the 2FA code step (useMfa + MfaCodeForm) — no recipe needed.
  mfaStep: boolean
}

export interface PrettierInfo {
  config: string
  bin: string
}

export type UiKit =
  | {
      kind: 'shadcn'
      // Directory of the shadcn components, relative to the project root.
      dir: string
      // Import specifiers from components.json (or derived from the alias).
      uiImport: string | null
      utilsImport: string | null
      // Newer shadcn <DialogContent> has `showCloseButton`; older versions do not.
      dialogCloseButtonProp: boolean
    }
  | { kind: 'plain'; reason: string }

export interface DetectOptions {
  framework?: Framework
  // --env-var: explicit env variable name for the API base URL.
  envVar?: string
}

export interface ProjectInfo {
  root: string
  framework: Framework
  frameworkLabel: string
  reactRouter: boolean
  vueRouter: boolean
  // App source dir relative to root ('app' for React Router 7, 'src' for Vue).
  appDir: string
  // Import alias pointing at appDir (e.g. '~/', '@/'); null = relative imports.
  alias: string | null
  ui: UiKit
  tailwind: boolean
  // Toast actually used by the app (imports in the source, shadcn toast/sonner component).
  toast: ToastInfo | null
  // Toast packages listed in package.json but not used anywhere (report note only).
  unusedToastDeps: string[]
  env: EnvInfo
  // Existing /login page of the app (not generated by init) — init then prints a merge
  // recipe instead of generating LoginForm.
  loginPage: LoginPageInfo | null
  // Existing wiring found in the app (manual steps that are already done are skipped).
  wiring: {
    // Vue: VueQueryPlugin + createAuth in main.ts, in this order. React: AuthProvider in root.
    provider: 'ok' | 'wrong-order' | 'missing'
    dialogs: boolean
    boundary: boolean
  }
  prettier: PrettierInfo | null
  // Packages the generated code needs but package.json does not list.
  missingDeps: string[]
}

export class DetectError extends Error {
  override name = 'DetectError'
}

type PackageJson = {
  prettier?: unknown
  dependencies?: Record<string, string>
  devDependencies?: Record<string, string>
  peerDependencies?: Record<string, string>
}

type TsConfig = {
  extends?: string | string[]
  references?: { path: string }[]
  compilerOptions?: {
    baseUrl?: string
    paths?: Record<string, string[]>
  }
}

const SHADCN_COMPONENTS = ['button', 'dialog', 'input', 'label', 'checkbox'] as const
// shadcn-vue: one directory per component (components/ui/button/index.ts). The Vue
// templates use a native checkbox, so `checkbox` is not required.
const SHADCN_VUE_COMPONENTS = ['button', 'dialog', 'input', 'label'] as const

export const DEFAULT_ENV_KEY = 'VITE_API_BASE_URL'
// Env files read by Vite (plus the example), in the order they are reported.
const ENV_FILES = [
  '.env',
  '.env.local',
  '.env.development',
  '.env.development.local',
  '.env.production',
  '.env.production.local',
  '.env.example',
]
// Known names of the API base URL variable, most specific first.
const ENV_KEY_CANDIDATES = [
  'VITE_API_BASE_URL',
  'VITE_BACKEND_URL',
  'VITE_API_URL',
  'VITE_AUTH_URL',
]
const SOURCE_EXTENSIONS = ['.ts', '.tsx', '.js', '.jsx', '.vue']
const SKIPPED_DIRS = new Set(['node_modules', 'dist', 'build', '.react-router', '.output', 'ui'])

function readJsonFile<T>(file: string): T | null {
  if (!existsSync(file)) return null
  try {
    return parseJsonc(readFileSync(file, 'utf8')) as T
  } catch {
    return null
  }
}

// First number of a semver range ('^7.13.0' → 7). null = unknown (workspace:*, latest, git url).
export function majorOf(range: string | undefined): number | null {
  if (!range) return null
  const match = /(\d+)/.exec(range)
  return match ? Number(match[1]) : null
}

function atLeast(range: string | undefined, major: number): boolean {
  if (range === undefined) return false
  const parsed = majorOf(range)
  return parsed === null || parsed >= major
}

function toPosix(path: string): string {
  return path.split(sep).join('/')
}

// Collects `compilerOptions.paths` from tsconfig.json and the configs it extends /
// references (create-vue keeps paths in tsconfig.app.json). Targets are resolved to
// project-root-relative posix paths.
function collectPaths(root: string): Map<string, string[]> {
  const result = new Map<string, string[]>()
  const visited = new Set<string>()

  const visit = (file: string) => {
    const abs = resolve(file)
    if (visited.has(abs)) return
    visited.add(abs)
    const config = readJsonFile<TsConfig>(abs)
    if (!config) return
    const dir = dirname(abs)

    const extendsList = Array.isArray(config.extends)
      ? config.extends
      : config.extends
        ? [config.extends]
        : []
    for (const ext of extendsList) {
      // Only local configs — package presets (@tsconfig/*) never declare app aliases.
      if (ext.startsWith('.')) visit(resolve(dir, ext.endsWith('.json') ? ext : `${ext}.json`))
    }

    const options = config.compilerOptions
    if (options?.paths) {
      const base = resolve(dir, options.baseUrl ?? '.')
      for (const [key, targets] of Object.entries(options.paths)) {
        result.set(
          key,
          targets.map((target) => toPosix(relative(root, resolve(base, target)))),
        )
      }
    }

    for (const ref of config.references ?? []) {
      const refPath = resolve(dir, ref.path)
      visit(refPath.endsWith('.json') ? refPath : join(refPath, 'tsconfig.json'))
    }
  }

  visit(join(root, 'tsconfig.json'))
  return result
}

function detectAlias(root: string, appDir: string, preferred: string[]): string | null {
  const paths = collectPaths(root)
  const matching: string[] = []
  for (const [key, targets] of paths) {
    if (!key.endsWith('/*')) continue
    if (targets.some((target) => target === `${appDir}/*`)) matching.push(key.slice(0, -1))
  }
  for (const alias of preferred) {
    if (matching.includes(alias)) return alias
  }
  return matching[0] ?? null
}

function detectUi(root: string, appDir: string, framework: Framework): UiKit {
  const componentsJson = readJsonFile<{ aliases?: { ui?: string; utils?: string } }>(
    join(root, 'components.json'),
  )
  if (!componentsJson) return { kind: 'plain', reason: 'brak components.json' }

  const candidates = [`${appDir}/components/ui`, 'app/components/ui', 'src/components/ui']
  const required: readonly string[] =
    framework === 'vue' ? SHADCN_VUE_COMPONENTS : SHADCN_COMPONENTS
  const componentFile = (dir: string, name: string) =>
    framework === 'vue' ? join(root, dir, name, 'index.ts') : join(root, dir, `${name}.tsx`)
  const dir = candidates.find((candidate) =>
    required.every((name) => existsSync(componentFile(candidate, name))),
  )
  if (!dir) {
    return {
      kind: 'plain',
      reason: `components.json jest, ale brak kompletu komponentów (${required.join(', ')}) w components/ui`,
    }
  }
  const dialogSource =
    framework === 'vue' ? '' : readFileSync(join(root, dir, 'dialog.tsx'), 'utf8')
  return {
    kind: 'shadcn',
    dir,
    uiImport: componentsJson.aliases?.ui ?? null,
    utilsImport: componentsJson.aliases?.utils ?? null,
    dialogCloseButtonProp: dialogSource.includes('showCloseButton'),
  }
}

// App source files (skips node_modules, build output and the generated shadcn ui/ dir).
function listSourceFiles(root: string, appDir: string): string[] {
  const out: string[] = []
  const walk = (dir: string) => {
    let entries: string[]
    try {
      entries = readdirSync(dir)
    } catch {
      return
    }
    for (const entry of entries) {
      if (out.length >= 5000) return
      const abs = join(dir, entry)
      let isDir = false
      try {
        isDir = statSync(abs).isDirectory()
      } catch {
        continue
      }
      if (isDir) {
        if (!SKIPPED_DIRS.has(entry) && !entry.startsWith('.')) walk(abs)
      } else if (SOURCE_EXTENSIONS.some((ext) => entry.endsWith(ext))) {
        out.push(abs)
      }
    }
  }
  walk(join(root, appDir))
  return out
}

function readText(file: string): string | null {
  try {
    return readFileSync(file, 'utf8')
  } catch {
    return null
  }
}

function stripExtension(path: string): string {
  return path.replace(/\.(?:ts|tsx|js|jsx|mjs|vue)$/, '')
}

// Import specifier → app-dir-relative module path (alias or relative), null for packages.
function toAppModule(
  root: string,
  appDir: string,
  alias: string | null,
  fromFile: string,
  specifier: string,
): string | null {
  if (alias && specifier.startsWith(alias)) return stripExtension(specifier.slice(alias.length))
  if (specifier.startsWith('.')) {
    const rel = toPosix(relative(join(root, appDir), resolve(dirname(fromFile), specifier)))
    return rel.startsWith('..') ? null : stripExtension(rel)
  }
  return null
}

const IMPORT_RE = /(?:import|export)\s[^'"]*?from\s*['"]([^'"]+)['"]/g

// Toast actually used by the app: imports in the source decide (the most used one wins);
// without imports — a shadcn toast / sonner component in components/ui. A package that is
// only listed in package.json does not count (it may be a leftover of a shadcn install).
function detectToast(
  root: string,
  appDir: string,
  alias: string | null,
  framework: Framework,
  sources: string[],
): ToastInfo | null {
  const sonnerKind: ToastKind = framework === 'vue' ? 'vue-sonner' : 'sonner'
  const counts = new Map<string, { info: ToastInfo; count: number }>()
  const add = (info: ToastInfo) => {
    const key = `${info.kind}:${info.module}`
    const entry = counts.get(key)
    if (entry) entry.count += 1
    else counts.set(key, { info, count: 1 })
  }
  for (const file of sources) {
    const text = readText(file)
    if (!text) continue
    const rel = toPosix(relative(root, file))
    for (const match of text.matchAll(IMPORT_RE)) {
      const specifier = match[1] as string
      if (specifier === 'sonner' || specifier === 'vue-sonner') {
        add({ kind: specifier, module: specifier, appModule: false, source: rel })
        continue
      }
      if (!/(?:^|\/)use-toast$|\/ui\/toast(?:\/index)?$/.test(stripExtension(specifier))) continue
      if (!/\btoast\b/.test(match[0])) continue
      const module = toAppModule(root, appDir, alias, file, specifier)
      if (module) add({ kind: 'use-toast', module, appModule: true, source: rel })
    }
  }
  const best = [...counts.values()].sort((a, b) => b.count - a.count)[0]
  if (best) return best.info

  const ui = (path: string) => existsSync(join(root, appDir, 'components/ui', path))
  if (ui('sonner.tsx') || ui('sonner/index.ts')) {
    return {
      kind: sonnerKind,
      module: sonnerKind,
      appModule: false,
      source: 'components/ui/sonner',
    }
  }
  for (const module of [
    'components/ui/toast/use-toast',
    'components/ui/use-toast',
    'hooks/use-toast',
  ]) {
    if (['.ts', '.tsx'].some((ext) => existsSync(join(root, appDir, `${module}${ext}`)))) {
      return { kind: 'use-toast', module, appModule: true, source: module }
    }
  }
  return null
}

function parseEnvKeys(text: string): Map<string, string> {
  const keys = new Map<string, string>()
  for (const line of text.split(/\r?\n/)) {
    const match = /^\s*(?:export\s+)?([A-Z0-9_]+)\s*=\s*(.*)$/.exec(line)
    if (match) keys.set(match[1] as string, (match[2] as string).trim().replace(/^['"]|['"]$/g, ''))
  }
  return keys
}

// API base URL variable: --env-var → baseUrl in an existing lib/auth.ts → a known name in
// the env files → default VITE_API_BASE_URL.
function detectEnv(root: string, appDir: string, explicit?: string): EnvInfo {
  const envFiles = ENV_FILES.map((file) => ({ file, text: readText(join(root, file)) })).filter(
    (entry): entry is { file: string; text: string } => entry.text !== null,
  )
  const parsed = envFiles.map(({ file, text }) => ({ file, keys: parseEnvKeys(text) }))

  let key: string | null = explicit ?? null
  let source = explicit ? '--env-var' : ''
  if (!key) {
    for (const file of ['lib/auth.ts', 'lib/auth.js']) {
      const text = readText(join(root, appDir, file))
      const match = text && /baseUrl\s*:\s*import\.meta\.env\.([A-Z0-9_]+)/.exec(text)
      if (match) {
        key = match[1] as string
        source = `${appDir}/${file}`
        break
      }
    }
  }
  if (!key) {
    const all = parsed.flatMap(({ file, keys }) => [...keys.keys()].map((name) => ({ file, name })))
    const known = ENV_KEY_CANDIDATES.map((name) => all.find((entry) => entry.name === name)).find(
      Boolean,
    )
    const guessed = known ?? all.find((entry) => /^VITE_\w*(?:API|BACKEND)\w*URL$/.test(entry.name))
    if (guessed) {
      key = guessed.name
      source = guessed.file
    }
  }
  if (!key) {
    key = DEFAULT_ENV_KEY
    source = 'domyślna'
  }
  const definedIn = parsed.filter(({ keys }) => keys.has(key)).map(({ file }) => file)
  const hasValue = parsed.some(
    ({ file, keys }) => file !== '.env.example' && (keys.get(key) ?? '') !== '',
  )
  return { key, source, definedIn, hasValue }
}

export const GENERATED_MARKER = '@musikhood-dev/auth-client init'

// Existing /login page of the app. Vue: `path: '/login'` in the router (component from a
// static or lazy import). React Router 7: `route('login', '<file>')` in routes.ts. Pages
// generated by init (marker) do not count.
function detectLoginPage(
  root: string,
  appDir: string,
  alias: string | null,
  framework: Framework,
): LoginPageInfo | null {
  const hasMfaStep = (pageFile: string | null) => {
    const text = pageFile ? readText(join(root, pageFile)) : null
    return text !== null && text.includes('useMfa') && /MfaCodeForm|mfa-code-form/.test(text)
  }
  const isOwnPage = (pageFile: string | null) => {
    if (!pageFile) return false
    const text = readText(join(root, pageFile))
    return text === null || text.includes(GENERATED_MARKER)
  }

  if (framework === 'react') {
    const routesFile = `${appDir}/routes.ts`
    const routes = readText(join(root, routesFile))
    if (!routes) return null
    const match = /route\(\s*['"]\/?login['"]\s*,\s*['"]([^'"]+)['"]/.exec(routes)
    if (!match) return null
    const pageFile = toPosix(join(appDir, match[1] as string))
    return isOwnPage(pageFile)
      ? null
      : { routeFile: routesFile, pageFile, mfaStep: hasMfaStep(pageFile) }
  }

  const candidates = [
    'router/index.ts',
    'router/index.js',
    'router.ts',
    'router.js',
    'main.ts',
    'main.js',
  ]
  for (const candidate of candidates) {
    const routeFile = `${appDir}/${candidate}`
    const abs = join(root, routeFile)
    const text = readText(abs)
    if (!text) continue
    const pathMatch = /path\s*:\s*['"]\/login['"]/.exec(text)
    if (!pathMatch) continue
    // The route object around `path: '/login'` — up to the next closing brace.
    const block = text.slice(pathMatch.index, text.indexOf('}', pathMatch.index) + 1)
    let specifier: string | null = null
    const lazy = /component\s*:\s*\(\)\s*=>\s*import\(\s*['"]([^'"]+)['"]/.exec(block)
    if (lazy) specifier = lazy[1] as string
    const named = /component\s*:\s*([A-Za-z_$][\w$]*)/.exec(block)
    if (!specifier && named) {
      const imported = new RegExp(`import\\s+${named[1]}\\s+from\\s*['"]([^'"]+)['"]`).exec(text)
      if (imported) specifier = imported[1] as string
    }
    let pageFile: string | null = null
    const module = specifier ? toAppModule(root, appDir, alias, abs, specifier) : null
    if (module) {
      const candidates = ['.vue', '.ts', '.js', '/index.vue', '/index.ts'].map(
        (ext) => `${appDir}/${module}${ext}`,
      )
      pageFile =
        candidates.find((file) => existsSync(join(root, file))) ?? `${appDir}/${module}.vue`
    }
    return isOwnPage(pageFile) ? null : { routeFile, pageFile, mfaStep: hasMfaStep(pageFile) }
  }
  return null
}

// Manual steps already done in the app (provider plugin / AuthProvider, dialogs, boundary).
function detectWiring(
  root: string,
  appDir: string,
  framework: Framework,
  reactRouter: boolean,
  sources: string[],
): ProjectInfo['wiring'] {
  const usesBoundary = sources.some((file) => {
    const text = readText(file)
    return text !== null && !text.includes(GENERATED_MARKER) && text.includes('<AuthBoundary')
  })
  if (framework === 'vue') {
    const main = readText(join(root, appDir, 'main.ts')) ?? readText(join(root, appDir, 'main.js'))
    const app = readText(join(root, appDir, 'App.vue')) ?? ''
    let provider: 'ok' | 'wrong-order' | 'missing' = 'missing'
    if (main) {
      const query = main.search(/\.use\(\s*VueQueryPlugin/)
      const auth = main.search(/\.use\(\s*createAuth\(/)
      if (query >= 0 && auth >= 0) provider = query < auth ? 'ok' : 'wrong-order'
    }
    return { provider, dialogs: app.includes('AuthMfaDialogs'), boundary: usesBoundary }
  }
  const rootFile = reactRouter ? 'root.tsx' : 'main.tsx'
  const rootText = readText(join(root, appDir, rootFile)) ?? ''
  return {
    provider: rootText.includes('<AuthProvider') ? 'ok' : 'missing',
    dialogs: rootText.includes('AuthMfaDialogs'),
    boundary: usesBoundary,
  }
}

const PRETTIER_CONFIGS = [
  '.prettierrc',
  '.prettierrc.json',
  '.prettierrc.json5',
  '.prettierrc.yaml',
  '.prettierrc.yml',
  '.prettierrc.toml',
  '.prettierrc.js',
  '.prettierrc.cjs',
  '.prettierrc.mjs',
  'prettier.config.js',
  'prettier.config.cjs',
  'prettier.config.mjs',
  'prettier.config.ts',
]

// Prettier config of the repo + a locally installed prettier (node_modules up the tree).
// Both are needed — init never downloads anything.
function detectPrettier(root: string, pkg: { prettier?: unknown }): PrettierInfo | null {
  let config: string | null = pkg.prettier !== undefined ? 'package.json#prettier' : null
  let bin: string | null = null
  let dir = root
  for (;;) {
    if (!config) {
      const found = PRETTIER_CONFIGS.find((name) => existsSync(join(dir, name)))
      if (found) config = toPosix(relative(root, join(dir, found))) || found
    }
    if (!bin) {
      const candidate = join(dir, 'node_modules/prettier/bin/prettier.cjs')
      if (existsSync(candidate)) bin = candidate
    }
    if ((config && bin) || existsSync(join(dir, '.git'))) break
    const parent = dirname(dir)
    if (parent === dir) break
    dir = parent
  }
  return config && bin ? { config, bin } : null
}

export function detectProject(root: string, options: DetectOptions = {}): ProjectInfo {
  const override = options.framework
  const pkg = readJsonFile<PackageJson>(join(root, 'package.json'))
  if (!pkg) throw new DetectError(`Nie znaleziono package.json w ${root}`)
  const deps: Record<string, string> = {
    ...pkg.peerDependencies,
    ...pkg.devDependencies,
    ...pkg.dependencies,
  }

  const reactRouter = '@react-router/dev' in deps || atLeast(deps['react-router'], 7)
  const isVue = atLeast(deps.vue, 3)
  const isReact = 'react' in deps

  let framework: Framework
  if (override) framework = override
  else if (reactRouter) framework = 'react'
  else if (isVue) framework = 'vue'
  else if (isReact) framework = 'react'
  else {
    throw new DetectError(
      'Nie rozpoznano frameworka (oczekiwano React Router 7 albo Vue 3 w package.json). Użyj --framework react|vue.',
    )
  }

  const hasDir = (dir: string) => existsSync(join(root, dir))
  const appDir =
    framework === 'vue'
      ? 'src'
      : reactRouter
        ? hasDir('app') || !hasDir('src')
          ? 'app'
          : 'src'
        : hasDir('src') || !hasDir('app')
          ? 'src'
          : 'app'

  const alias = detectAlias(root, appDir, framework === 'vue' ? ['@/', '~/'] : ['~/', '@/'])

  const ui = detectUi(root, appDir, framework)
  const sources = listSourceFiles(root, appDir)
  const toast = detectToast(root, appDir, alias, framework, sources)
  const unusedToastDeps = ['sonner', 'vue-sonner'].filter(
    (name) => name in deps && toast?.module !== name,
  )

  const required =
    framework === 'react'
      ? ['@musikhood-dev/auth-client', '@tanstack/react-query']
      : ['@musikhood-dev/auth-client', '@tanstack/vue-query']
  const reactRouterUsed = framework === 'react' && reactRouter

  return {
    root,
    framework,
    frameworkLabel:
      framework === 'vue' ? 'Vue 3' : reactRouter ? 'React Router 7' : 'React (bez React Router 7)',
    reactRouter: reactRouterUsed,
    vueRouter: framework === 'vue' && 'vue-router' in deps,
    appDir,
    alias,
    ui,
    tailwind: 'tailwindcss' in deps || '@tailwindcss/vite' in deps,
    toast,
    unusedToastDeps,
    env: detectEnv(root, appDir, options.envVar),
    loginPage: detectLoginPage(root, appDir, alias, framework),
    wiring: detectWiring(root, appDir, framework, reactRouterUsed, sources),
    prettier: detectPrettier(root, pkg),
    missingDeps: required.filter((name) => !(name in deps)),
  }
}
